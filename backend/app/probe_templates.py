"""Библиотека шаблонов вопросов Contextual Probe.

Это не банк готовых вопросов: в каждом шаблоне есть слот, куда подставляется
конкретная деталь из материалов самого кандидата (§5.2 FRD). Один и тот же
шаблон у двух разных людей даёт разные вопросы, потому что цитата разная.

`slot`:
  quote  - фрагмент из описания кандидата, вопрос строится вокруг него;
  source - ссылка или файл, который кандидат приложил;
  none   - запасной путь (FR2.4): артефакта не нашлось, вопрос опирается
           только на компетенцию. Такие шаблоны помечены `grounded=False`,
           чтобы в аналитике их было видно отдельно;
  nda    - переформулировка после отказа по NDA (FR5.2): тот же предмет
           проверки, но без привязки к конкретному проекту - вопрос про логику
           решений вообще, а не про закрытый материал.

Все формулировки открытые - «почему», «как», «что бы вы сделали, если». Ни
вариантов ответа, ни единственно верной строки здесь нет и быть не может
(US3): правильность ответа не сверяется со сохранённым ключом.

`expected_terms` - «ловушка на жаргон» (FR3.2): слова, которые практик почти
неизбежно упомянет, отвечая по существу. Отдельного детектора нет и не должно
быть: если ни одного слова нет, задаётся один уточняющий вопрос, не более.
"""

